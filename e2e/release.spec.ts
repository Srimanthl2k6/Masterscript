test('automatic breakdown edits, rejections and report exports share the saved project', async ({ page }) => {
  await page.goto('/#/app')
  await page.getByRole('button', { name: 'New Project', exact: true }).click()
  const heading = page.getByRole('textbox', { name: 'scene-heading screenplay block' }).first()
  await heading.fill('INT. HOSPITAL - NIGHT')
  await heading.press('End')
  await heading.press('Enter')
  await page.getByRole('textbox', { name: 'action screenplay block' }).first().fill("RAVI lies unconscious on the bed. Maya enters carrying Ravi's backpack. A NURSE follows her. She checks the heart monitor.")
  await page.getByRole('button', { name: 'Breakdown', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Scene Breakdown' })).toBeVisible()
  const bag = page.locator('.tag-catalog-item').filter({ has: page.locator('input[value="backpack"]') })
  await expect(bag).toBeVisible()
  await bag.getByLabel('Notes').fill('Hero prop')
  await bag.getByLabel('Cost').fill('25')
  await bag.getByLabel('Item', { exact: true }).fill('Ravi bag')
  const edited = page.locator('.tag-catalog-item').filter({ has: page.locator('input[value="Ravi bag"]') })
  await page.getByRole('button', { name: 'Reanalyse', exact: true }).click()
  await expect(edited.getByLabel('Notes')).toHaveValue('Hero prop')
  await expect(edited.getByLabel('Cost')).toHaveValue('25')
  const monitor = page.locator('.tag-catalog-item').filter({ has: page.locator('input[value="heart monitor"]') })
  await monitor.getByRole('button', { name: 'Reject', exact: true }).click()
  await page.getByRole('button', { name: 'Reanalyse', exact: true }).click()
  await expect(monitor).toHaveCount(0)
  const overflowingFields = await page.locator('.tag-catalog-item').evaluateAll(items => items.flatMap(item => {
    const card = item.getBoundingClientRect()
    return [...item.querySelectorAll('input, select')].filter(field => field.getBoundingClientRect().right > card.right + 1)
  }).length)
  expect(overflowingFields).toBe(0)
  await page.screenshot({ path: 'test-results/breakdown.png', fullPage: true })
  await page.getByRole('button', { name: 'Reports', exact: true }).click()
  await expect(page.getByText('Ravi bag', { exact: false }).first()).toBeVisible()
  await page.getByLabel('Report type').selectOption('department')
  await page.getByLabel('Report department').selectOption('Props')
  await expect(page.locator('.report-table').getByText('Hero prop', { exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click()
  expect((await download).suggestedFilename()).toMatch(/\.csv$/)
  await page.waitForTimeout(1600)
  const saved = await page.evaluate(() => Object.values(localStorage).map(value => { try { return JSON.parse(value) } catch { return null } }).find(value => value?.tagging?.catalog?.some((item: { name: string }) => item.name === 'Ravi bag')))
  expect(saved.tagging.rejectedItems).toContain('Set Dressing:heart monitor')
})
